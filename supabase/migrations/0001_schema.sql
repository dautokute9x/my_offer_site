-- search_text: giống searchText() trong lib/data/demo.ts.
create function job_search_text(j jobs) returns text language sql stable set search_path = public as $$
  select norm_text(concat_ws(' ', j.code, j.title_vi, j.title_ja, j.location_detail_ja,
    (select string_agg(array_to_string(p.aliases, ' '), ' ' order by p.id)
       from job_prefectures jp join prefectures p on p.id = jp.prefecture_id where jp.job_id = j.id),
    (select string_agg(concat_ws(' ', o.name_vi, o.name_ja, array_to_string(o.aliases, ' ')), ' ' order by o.id)
       from job_occupations jo join occupations o on o.id = jo.occupation_id where jo.job_id = j.id),
    (select string_agg(concat_ws(' ', s.name, array_to_string(s.aliases, ' ')), ' ' order by s.id)
       from job_skills js join skills s on s.id = js.skill_id where js.job_id = j.id)))
$$;

create function jobs_before_write() returns trigger language plpgsql set search_path = public as $$
begin
  new.search_text := job_search_text(new);
  -- Chỉ đổi updated_at khi nội dung đổi; trigger bảng nối chỉ cập nhật search_text.
  if tg_op = 'UPDATE' and (to_jsonb(new) - 'search_text' - 'updated_at') is distinct from (to_jsonb(old) - 'search_text' - 'updated_at') then
    new.updated_at := now();
  end if;
  return new;
end $$;
create trigger jobs_search_text before insert or update on jobs for each row execute function jobs_before_write();

create function job_links_touch() returns trigger language plpgsql set search_path = public as $$
begin
  update jobs j set search_text = job_search_text(j)
   where j.id in (new.job_id, old.job_id);  -- NEW/OLD là null khi không áp dụng
  return null;
end $$;
create trigger job_prefectures_search_text after insert or update or delete on job_prefectures
  for each row execute function job_links_touch();
create trigger job_occupations_search_text after insert or update or delete on job_occupations
  for each row execute function job_links_touch();
create trigger job_skills_search_text after insert or update or delete on job_skills
  for each row execute function job_links_touch();

create function is_admin() returns bool
language sql stable security definer set search_path = public as $$
  select exists (select 1 from admins where user_id = auth.uid())
$$;
revoke execute on function is_admin() from public;
grant execute on function is_admin() to anon, authenticated, service_role;

-- RLS. service_role bỏ qua RLS. anon/authenticated chỉ đọc phần công khai; admin làm mọi thao tác.
do $$ declare t text;
begin
  foreach t in array array['prefectures', 'occupation_groups', 'occupations', 'skills', 'benefits', 'jobs',
    'job_prefectures', 'job_occupations', 'job_skills', 'job_benefits', 'interview_events',
    'applications', 'application_notes', 'admins', 'site_settings'] loop
    execute format('alter table %I enable row level security', t);
    execute format('create policy admin_all on %I for all to authenticated using ((select is_admin())) with check ((select is_admin()))', t);
  end loop;
  foreach t in array array['prefectures', 'occupation_groups', 'occupations', 'skills', 'benefits', 'site_settings'] loop
    execute format('create policy public_read on %I for select to anon, authenticated using (true)', t);
  end loop;
  foreach t in array array['job_prefectures', 'job_occupations', 'job_skills', 'job_benefits', 'interview_events'] loop
    execute format('create policy public_read on %I for select to anon, authenticated using (exists (
      select 1 from jobs j where j.id = job_id and j.status in (''published'', ''closed'')))', t);
  end loop;
end $$;
create policy public_read on jobs for select to anon, authenticated using (status in ('published', 'closed'));

