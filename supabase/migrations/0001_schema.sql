-- Phải cho cùng kết quả với normText() trong lib/normalize.ts. Bỏ dấu bằng NFD + xóa dải U+0300–U+036F
-- thay vì unaccent: unaccent còn đổi ký tự khác (æ→ae…) nên sẽ lệch với TS; dải này không chạm dakuten của kana.
create function norm_text(t text) returns text
language sql immutable parallel safe set search_path = pg_catalog as $$
  select normalize(btrim(regexp_replace(replace(regexp_replace(
    normalize(lower(normalize(t, NFKC)), NFD), '[\u0300-\u036f]', '', 'g'), 'đ', 'd'), '\s+', ' ', 'g'), ' '), NFC)
$$;

